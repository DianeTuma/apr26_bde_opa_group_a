import streamlit as st
import requests

st.title("🔮 Live Market Prediction")
st.subheader("Fetch the latest ML decision generated by the real-time streaming data")

# User selects the market they want to view
market = st.selectbox("Select Market:", ["BTCUSDT", "ETHUSDT", "BNBUSDT"])

st.markdown("---")

# --- ML Model Overview Section ---
st.header("ML Model Overview")
st.info("🧠 ML-Model : Random Forest Classifier")
st.markdown(
    "The ML model analyzes the latest streaming market data and generates real-time trading signals "
    "for the upcoming candle. It is trained on deep historical price data "
    "and advanced technical indicators to make informed predictions."
)
st.write("") 

# Initialize session state variables to prevent crashes on initial load
if "latest_decision" not in st.session_state:
    st.session_state["latest_decision"] = None
    st.session_state["latest_probability"] = None
    st.session_state["full_prediction"] = None
    st.session_state["has_searched"] = False

# --- ACTION: Trigger Model Analysis ---
if st.button("Run the Model Analysis", type="primary"):
    api_url = f"http://api:8000/latest-prediction?market={market}"
    
    try:
        with st.spinner("Fetching latest data from API..."):
            response = requests.get(api_url)
            
        if response.status_code == 200:
            result = response.json()
            prediction = result["latest_prediction"]
            
            st.success(f"Successfully retrieved live data for {result['market']}!")
            st.session_state["has_searched"] = True
            st.session_state["full_prediction"] = prediction
            
            # Map values using the exact keys returned by predict.py
            st.session_state["latest_decision"] = prediction.get("recommended_action", "HOLD/SELL")
            st.session_state["latest_probability"] = prediction.get("buy_probability", 0.0)
                
        else:
            st.error(f"❌ API Error {response.status_code}: {response.json().get('detail', response.text)}")
            
    except requests.exceptions.ConnectionError:
        st.error(" Unable to contact the API server. Is FastAPI running in Docker?")

# --- DYNAMIC RESULTS DISPLAY ---
if st.session_state["has_searched"]:
    st.markdown("---")
    st.header("Trading Recommendation")
    
    decision = st.session_state["latest_decision"]
    probability = st.session_state["latest_probability"]
    
    # Format probability as a clean percentage (e.g., 0.7245 -> 72.45%)
    prob_percentage = f"{probability * 100:.2f}%" if isinstance(probability, float) else probability
    
    message_text = f"The trading recommendation for the upcoming candle is: **{decision}** (Buy Probability: {prob_percentage})"
    
    # Dynamic coloring based on the model's action
    if decision == "BUY":
        st.success(f"🟢 {message_text}")
    else:
        # Handles the "HOLD/SELL" case neutrally
        st.warning(f"⚪ {message_text}")
        
    # Collapsible container for raw JSON debugging
    with st.expander("📊 View Detailed Model Payload (JSON)"):
        st.json(st.session_state["full_prediction"])
else:
    # Only displayed before the user performs their first analysis
    st.info("💡 Click on **'Run the Model Analysis'** above to fetch the latest signal.")